import puppeteer from 'puppeteer'
const b = await puppeteer.launch({headless:true, protocolTimeout:120000, args:['--no-sandbox','--disable-dev-shm-usage']})
const p = await b.newPage()
const logs=[]
p.on('console', m=>logs.push(m.type()+': '+m.text().slice(0,180)))
p.on('pageerror', e=>logs.push('pageerror: '+e.message.slice(0,300)))
await p.setViewport({width:1440,height:900})
await p.goto('http://localhost:8080/host.html',{waitUntil:'networkidle2'})
await new Promise(r=>setTimeout(r,2200))
const F=()=>p.frames().find(x=>x.url().includes('lumina-library-preview'))
const ev=(fn,...a)=>F().evaluate(fn,...a)
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms))
await ev(()=>{ const a=Array.from(document.querySelectorAll('a')).find(a=>a.innerText.includes('Sign in')); a?.click() })
await sleep(1200)
await ev(()=>{ Array.from(document.querySelectorAll('button')).find(b=>b.innerText.includes('Enter Administrator demo'))?.click() })
await sleep(2200)
await ev(()=>{ const a=Array.from(document.querySelectorAll('a')).find(a=>a.getAttribute('href')==='#/app/books'); a?.click() })
await sleep(1600)
await ev(()=>{ Array.from(document.querySelectorAll('button')).find(b=>b.innerText.trim()==='Add book')?.click() })
await sleep(900)
const fill=async(sel,val)=>{ await ev((s,v)=>{const el=document.querySelector(s); if(!el)return; const proto=el.tagName==='TEXTAREA'?window.HTMLTextAreaElement.prototype:window.HTMLInputElement.prototype; Object.getOwnPropertyDescriptor(proto,'value').set.call(el,v); el.dispatchEvent(new Event('input',{bubbles:true})); el.dispatchEvent(new Event('change',{bubbles:true}))},sel,val); await sleep(150) }
await fill('#book-form input[name="title"]','Sandbox Proof Title')
await fill('#book-form input[name="author"]','QA Bot')
await fill('#book-form input[name="publisher"]','Inline Press')
await fill('#book-form input[name="shelf"]','SB-01')
await fill('#book-form input[name="totalCopies"]','2')
const fields = await ev(()=>Array.from(document.querySelectorAll('#book-form input, #book-form select, #book-form textarea')).map(el=>({name:el.name, value:el.value})))
console.log('field values:', JSON.stringify(fields))
await ev(()=>{ const d=document.querySelector('[role=dialog]'); Array.from(d.querySelectorAll('button')).find(b=>b.innerText.includes('Add book'))?.click() })
await sleep(2500)
const dlg = await ev(()=>document.querySelector('[role=dialog]')?.innerText ?? 'dialog closed')
console.log('dialog text after submit:\n', dlg.slice(0,700))
console.log('alerts:', await ev(()=>Array.from(document.querySelectorAll('[role=alert]')).map(n=>n.innerText)))
console.log('page text has title:', (await ev(()=>document.body.innerText)).includes('Sandbox Proof Title'))
console.log('logs:', logs.filter(l=>!l.startsWith('debug')).slice(0,8))
await b.close()
