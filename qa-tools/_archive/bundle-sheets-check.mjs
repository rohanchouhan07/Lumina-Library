import puppeteer from 'puppeteer'
const b = await puppeteer.launch({headless:true, protocolTimeout:120000, args:['--no-sandbox','--disable-dev-shm-usage']})
const p = await b.newPage()
const errs = []
p.on('pageerror', (e) => errs.push('pageerror: ' + e.message.slice(0,160)))
p.on('console', (m) => { if (m.type()==='error' && !m.text().includes('404')) errs.push(m.text().slice(0,160)) })
await p.setViewport({width:1440,height:1000})
await p.goto('http://localhost:8080/host.html',{waitUntil:'networkidle2'})
await new Promise(r=>setTimeout(r,2200))
const F = () => p.frames().find(x=>x.url().includes('lumina-library-preview'))
const ev = (fn,...a) => F().evaluate(fn,...a)
await ev(()=>{ Array.from(document.querySelectorAll('a')).find(a=>a.innerText.includes('Sign in'))?.click() })
await new Promise(r=>setTimeout(r,1200))
await ev(()=>{ Array.from(document.querySelectorAll('button')).find(b=>b.innerText.includes('Enter Administrator demo'))?.click() })
await new Promise(r=>setTimeout(r,2200))
await ev(()=>{ Array.from(document.querySelectorAll('a')).find(a=>a.getAttribute('href')==='#/app/settings')?.click() })
await new Promise(r=>setTimeout(r,1800))
const text = await ev(()=>document.body.innerText)
console.log('panel present:', text.includes('Google Sheets sync'))
console.log('embedded warning shown:', text.includes('cannot reach Google'))
await ev(()=>{ Array.from(document.querySelectorAll('button')).find(b=>b.innerText.includes('Test connection'))?.click() })
await new Promise(r=>setTimeout(r,3000))
const after = await ev(()=>document.body.innerText)
console.log('graceful failure message:', /Could not reach Google Sheets|blocked/i.test(after))
const h = await p.$('#sheet-sync-heading')
if (h) {
  const section = await p.evaluateHandle((el)=>el.closest('section'), h)
  await section.scrollIntoView(); await new Promise(r=>setTimeout(r,600))
  await section.asElement().screenshot({path:'/home/user/qa-screens/sheets-7-embedded.png'})
}
console.log('page errors:', errs.length, errs.slice(0,3))
await b.close()
