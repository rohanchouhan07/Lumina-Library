import puppeteer from 'puppeteer'
const b = await puppeteer.launch({headless:true, protocolTimeout:120000, args:['--no-sandbox','--disable-dev-shm-usage']})
const p = await b.newPage()
await p.setViewport({width:1440,height:900})
await p.goto('http://localhost:5173/login', {waitUntil:'domcontentloaded'})
await new Promise(r=>setTimeout(r,900))
await p.evaluate(()=>{const el=Array.from(document.querySelectorAll('button')).find(b=>b.innerText.includes('Enter Administrator demo'));el?.click()})
await new Promise(r=>setTimeout(r,1800))
const txt = await p.evaluate(()=>document.body.innerText)
console.log('path:', await p.evaluate(()=>location.pathname))
console.log('has overview:', txt.toLowerCase().includes('administrator overview'))
console.log('has stat:', txt.includes('Total copies'), '| has chart data:', (await p.$$('.recharts-surface')).length, 'charts')
await p.screenshot({path:'/home/user/qa-screens/live-dashboard.png'})
await b.close()
