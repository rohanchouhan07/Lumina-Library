import puppeteer from 'puppeteer'
const b = await puppeteer.launch({headless:true, protocolTimeout:120000, args:['--no-sandbox','--disable-dev-shm-usage']})
const p = await b.newPage()
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms))
await p.setViewport({width:375,height:812})
await p.goto('http://localhost:5173/login',{waitUntil:'domcontentloaded'})
await sleep(500)
await p.evaluate(()=>{const el=Array.from(document.querySelectorAll('button')).find(b=>b.innerText.includes('Enter Administrator demo'));el?.click()})
await sleep(1600)
await p.evaluate(()=>{const el=Array.from(document.querySelectorAll('button[aria-label="Open navigation"]'))[0];el?.click()})
await sleep(700)
await p.screenshot({path:'/home/user/qa-screens/m-drawer.png'})
await p.keyboard.press('Escape')
await p.evaluate(()=>document.querySelector('[aria-modal="true"]')?.dispatchEvent(new Event('x')))
await p.goto('http://localhost:5173/app/loans',{waitUntil:'domcontentloaded'})
await sleep(1000)
await p.screenshot({path:'/home/user/qa-screens/m-loans.png', fullPage:true})
await p.setViewport({width:768,height:1024})
await p.goto('http://localhost:5173/',{waitUntil:'domcontentloaded'})
await sleep(1200)
await p.screenshot({path:'/home/user/qa-screens/t-landing.png'})
await b.close()
