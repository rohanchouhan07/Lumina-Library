import puppeteer from 'puppeteer'
const b = await puppeteer.launch({headless:true,args:['--no-sandbox']})
const p = await b.newPage()
await p.setViewport({width:1440,height:900})
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms))
const login = async (roleLabel) => {
  await p.goto('http://localhost:5173/login',{waitUntil:'networkidle2'})
  await p.evaluate((label)=>{const el=Array.from(document.querySelectorAll('button')).find(b=>b.innerText.trim().startsWith(label));el?.click()},roleLabel)
  await sleep(300)
  await p.evaluate((label)=>{const el=Array.from(document.querySelectorAll('button')).find(b=>b.innerText.includes(`Enter ${label} demo`));el?.click()},roleLabel)
  await sleep(1500)
}
await login('Student')
await p.screenshot({path:'/home/user/qa-screens/s-student.png',fullPage:true})
await p.goto('http://localhost:5173/app/books',{waitUntil:'networkidle2'}); await sleep(900)
await p.screenshot({path:'/home/user/qa-screens/s-books.png'})
await login('Administrator')
await p.goto('http://localhost:5173/app',{waitUntil:'networkidle2'}); await sleep(1200)
await p.screenshot({path:'/home/user/qa-screens/s-admin.png',fullPage:true})
await p.goto('http://localhost:5173/app/reports',{waitUntil:'networkidle2'}); await sleep(1600)
await p.screenshot({path:'/home/user/qa-screens/s-reports.png',fullPage:true})
await p.goto('http://localhost:5173/app/settings',{waitUntil:'networkidle2'}); await sleep(900)
await p.screenshot({path:'/home/user/qa-screens/s-settings.png',fullPage:true})
await p.goto('http://localhost:5173/app/profile',{waitUntil:'networkidle2'}); await sleep(900)
await p.screenshot({path:'/home/user/qa-screens/s-profile.png',fullPage:true})
await b.close()
